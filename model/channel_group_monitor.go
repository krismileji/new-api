func normalizeChannelGroupMonitorDisplay(value int, unit string) (int, string) {
	if IsChannelStatusProbeDisplayAllowed(value, unit) {
		return value, unit
	}
	return ChannelGroupMonitorDefaultDisplayValue, ChannelGroupMonitorDefaultDisplayUnit
}

func nextChannelGroupMonitorRunAt(after int64, intervalSeconds int) int64 {
	interval := int64(intervalSeconds)
	if after < 0 || interval <= 0 {
		return 0
	}
	return after - after%interval + interval
}

