// ChannelGroupMonitorGroup is the durable, ordered user-facing group list.
// A concrete probe model is required so a configuration change never silently
// changes the external traffic generated by the worker.
type ChannelGroupMonitorGroup struct {
	GroupName      string `json:"group_name"`
	ProbeModel     string `json:"probe_model"`
	DisplayInitial string `json:"display_initial,omitempty"`
}

type ChannelGroupMonitorConfig struct {
	Id                int64  `json:"id" gorm:"primaryKey"`
	Enabled           bool   `json:"enabled" gorm:"index:idx_channel_group_monitor_due,priority:1"`
	GroupsJSON        string `json:"-" gorm:"type:text;not null"`
	IntervalSeconds   int    `json:"interval_seconds"`
	DisplayValue      int    `json:"display_value"`
	DisplayUnit       string `json:"display_unit" gorm:"type:varchar(16)"`
	Revision          int64  `json:"revision" gorm:"bigint"`
	NextRunAt         int64  `json:"next_run_at" gorm:"bigint;index:idx_channel_group_monitor_due,priority:2"`
	ManualRequestId   string `json:"manual_request_id" gorm:"type:varchar(64);index:idx_channel_group_monitor_manual_due,priority:1"`
	ManualRequestedAt int64  `json:"manual_requested_at" gorm:"bigint;index:idx_channel_group_monitor_manual_due,priority:2,sort:desc"`
	LeaseToken        string `json:"-" gorm:"type:varchar(64)"`
	LeaseUntil        int64  `json:"lease_until" gorm:"bigint;index:idx_channel_group_monitor_due,priority:3;index:idx_channel_group_monitor_manual_due,priority:3"`
	RunningTrigger    string `json:"running_trigger" gorm:"type:varchar(16)"`
	RunningRunId      string `json:"running_run_id" gorm:"type:varchar(64)"`
	RunningStartedAt  int64  `json:"running_started_at" gorm:"bigint"`
	CreatedAt         int64  `json:"created_at" gorm:"bigint"`
	UpdatedAt         int64  `json:"updated_at" gorm:"bigint"`
}

func (config ChannelGroupMonitorConfig) Groups() ([]ChannelGroupMonitorGroup, error) {
	groups := []ChannelGroupMonitorGroup{}
	if strings.TrimSpace(config.GroupsJSON) == "" {
		return groups, nil
	}
	if err := common.UnmarshalJsonStr(config.GroupsJSON, &groups); err != nil {
		return nil, fmt.Errorf("解析分组监控配置失败: %w", err)
	}
	return groups, nil
}

