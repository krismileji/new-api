func GetChannelGroupMonitorExecutionsSince(startedAt int64) ([]ChannelGroupMonitorExecution, error) {
	var executions []ChannelGroupMonitorExecution
	err := DB.Where("finished_at >= ? AND result <> ?", startedAt, ChannelGroupMonitorResultSkipped).
		Order("group_name ASC, finished_at DESC, id DESC").Find(&executions).Error
	return executions, err
}

// GetChannelGroupMonitorExecutionWindowSince returns every execution in the
// requested time range, including skipped executions. The public monitor
// window uses skipped results to distinguish an empty time slot from a probe
// that was explicitly skipped, while the success-rate summary above keeps its
// historical non-skipped semantics.
func GetChannelGroupMonitorExecutionWindowSince(startedAt int64) ([]ChannelGroupMonitorExecution, error) {
	var executions []ChannelGroupMonitorExecution
	err := DB.Select("group_name, result, response_time_ms, first_token_ms, tps, finished_at").
		Where("finished_at >= ?", startedAt).
		Order("group_name ASC, finished_at ASC, id ASC").Find(&executions).Error
	return executions, err
}

func GetChannelGroupMonitorExecutionSummariesSince(startedAt int64) ([]ChannelGroupMonitorExecutionSummary, error) {
	var summaries []ChannelGroupMonitorExecutionSummary
	err := DB.Model(&ChannelGroupMonitorExecution{}).
		Select("group_name, result, COUNT(*) AS result_count").
		Where("finished_at >= ? AND result <> ?", startedAt, ChannelGroupMonitorResultSkipped).
		Group("group_name, result").
		Find(&summaries).Error
	return summaries, err
}

func ListChannelGroupMonitorExecutions(page int, pageSize int, groupName string, result string) ([]ChannelGroupMonitorExecution, int64, error) {
	query := DB.Model(&ChannelGroupMonitorExecution{})
	if strings.TrimSpace(groupName) != "" {
		query = query.Where("group_name = ?", strings.TrimSpace(groupName))
	}
	if strings.TrimSpace(result) != "" {
		query = query.Where("result = ?", strings.TrimSpace(result))
	}
	var total int64
	if err := query.Count(&total).Error; err != nil {
		return nil, 0, err
	}
	var executions []ChannelGroupMonitorExecution
	err := query.Order("finished_at DESC, id DESC").Offset((page - 1) * pageSize).Limit(pageSize).Find(&executions).Error
	return executions, total, err
}

func DeleteChannelGroupMonitorExecutionsBefore(
	ctx context.Context,
	cutoff int64,
	batchSize int,
	budget ChannelMonitorCleanupBudget,
) (int64, error) {
	if cutoff <= 0 || batchSize <= 0 {
		return 0, errors.New("分组监控历史清理参数无效")
	}
	if !DB.Migrator().HasTable(&ChannelGroupMonitorExecution{}) {
		return 0, nil
	}
	var deletedRows int64
	db := DB.WithContext(ctx)
	for {
		if budget.Exhausted() {
			return deletedRows, nil
		}
		var ids []int64
		if err := db.Model(&ChannelGroupMonitorExecution{}).
			Where("finished_at < ?", cutoff).
			Order("finished_at ASC, id ASC").
			Limit(batchSize).
			Pluck("id", &ids).Error; err != nil {
			return deletedRows, err
		}
		if len(ids) == 0 {
			return deletedRows, nil
		}
		deleted := db.Where("id IN ?", ids).Delete(&ChannelGroupMonitorExecution{})
		if deleted.Error != nil {
			return deletedRows, deleted.Error
		}
		deletedRows += deleted.RowsAffected
	}
}

func ChannelGroupMonitorGroupsByName(groups []ChannelGroupMonitorGroup) map[string]ChannelGroupMonitorGroup {
	byName := make(map[string]ChannelGroupMonitorGroup, len(groups))
	for _, group := range groups {
		byName[group.GroupName] = group
	}
	return byName
}

func SortChannelGroupMonitorGroups(groups []ChannelGroupMonitorGroup) {
	sort.Slice(groups, func(i int, j int) bool {
		return groups[i].GroupName < groups[j].GroupName
	})
}
