const (
	ChannelDailyCostRedisStream        = "channel_cost:v1:events"
	ChannelDailyCostRedisConsumerGroup = "channel-cost-ledger-v1"
	ChannelDailyCostRedisDeadLetter    = "channel_cost:v1:dead"

	channelDailyCostRedisFieldEventID = "event_id"
	channelDailyCostRedisFieldPayload = "payload"

	channelDailyCostOutboxBatchSize          = 256
	channelDailyCostOutboxPublishTimeout     = 250 * time.Millisecond
	channelDailyCostOutboxDBFallbackTimeout  = 750 * time.Millisecond
	channelDailyCostOutboxDBOperationTimeout = 3 * time.Second
	channelDailyCostOutboxReadBlock          = time.Second
	channelDailyCostOutboxClaimMinIdle       = 30 * time.Second
	channelDailyCostOutboxLeaseDuration      = 30 * time.Second
	channelDailyCostOutboxRecoveryInterval   = 500 * time.Millisecond
	channelDailyCostOutboxMaximumRetryDelay  = 5 * time.Minute
	channelDailyCostOutboxStatsInterval      = 5 * time.Second
	channelDailyCostOutboxCleanupInterval    = time.Hour
	channelDailyCostOutboxProcessedRetention = 30 * 24 * time.Hour
	channelDailyCostOutboxCleanupBatchSize   = 1_000
	channelDailyCostDeadLetterMaxLength      = 10_000
	// Cost payloads are generated by this service and are intentionally kept
	// bounded before they reach Redis or the JSON decoder. A malformed event
	// must be cheap to quarantine rather than becoming an unbounded allocation
	// or a shutdown-time Redis operation.
	channelDailyCostOutboxPayloadMaxLength = 64 * 1024
	channelDailyCostOutboxFailureMaxLength = 512
)

var channelDailyCostDeadLetterScript = redis.NewScript(`
local dead_letter_id = redis.call(
  "XADD", KEYS[1], "MAXLEN", "~", ARGV[1], "*",
  "original_message_id", ARGV[3],
  "event_id", ARGV[4],
  "payload", ARGV[5],
  "error", ARGV[6],
  "failed_at", ARGV[7]
)
redis.call("XACK", KEYS[2], ARGV[2], ARGV[3])
redis.call("XDEL", KEYS[2], ARGV[3])
return dead_letter_id
`)

