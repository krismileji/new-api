func channelDailyCostDeltaFromRedisMessage(message redis.XMessage) (model.ChannelDailyCostDelta, error) {
	eventID, ok := redisStringValue(message.Values[channelDailyCostRedisFieldEventID])
	eventID = strings.TrimSpace(eventID)
	if !ok || eventID == "" {
		return model.ChannelDailyCostDelta{}, errors.New("cost Stream event_id 缺失")
	}
	if len(eventID) > model.ChannelDailyCostOutboxEventIDMaxLength {
		return model.ChannelDailyCostDelta{}, errors.New("cost Stream event_id 过长")
	}
	payloadJSON, ok := redisStringValue(message.Values[channelDailyCostRedisFieldPayload])
	if !ok || payloadJSON == "" {
		return model.ChannelDailyCostDelta{}, errors.New("cost Stream payload 缺失")
	}
	if len(payloadJSON) > channelDailyCostOutboxPayloadMaxLength {
		return model.ChannelDailyCostDelta{}, errors.New("cost Stream payload 过大")
	}
	var payload channelDailyCostOutboxPayload
	if err := common.Unmarshal([]byte(payloadJSON), &payload); err != nil {
		return model.ChannelDailyCostDelta{}, err
	}
	delta := payload.delta(eventID)
	if err := model.ValidateChannelDailyCostDelta(delta); err != nil {
		return model.ChannelDailyCostDelta{}, err
	}
	return delta, nil
}

func redisStringValue(value interface{}) (string, bool) {
	switch typed := value.(type) {
	case string:
		return typed, true
	case []byte:
		return string(typed), true
	default:
		return "", false
	}
}

func nonNilContext(ctx context.Context) context.Context {
	if ctx == nil {
		return context.Background()
	}
	return ctx
}
